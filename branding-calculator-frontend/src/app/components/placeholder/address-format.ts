const addressTerms = new Map(Object.entries(addressAbbreviations));

// A prefix may already have been shortened while the rest of the term was being typed.
for (const [term, abbreviation] of Object.entries(addressAbbreviations)) {
  for (let index = term.indexOf(' '); index !== -1; index = term.indexOf(' ', index + 1)) {
    const shortenedPrefix = addressAbbreviations[term.slice(0, index)];
    if (shortenedPrefix) {
      addressTerms.set(shortenedPrefix.toLowerCase() + term.slice(index), abbreviation);
    }
  }
}

function alternatives(terms: Iterable<string>): string {
  return [...terms]
    .sort((first, second) => second.length - first.length)
    .map(term => term
      .replace(/[.*+?^$(){}|[\]\\]/g, '\\$&')
      .replace(/е/g, '[её]')
      .replace(/ /g, '\\s+'))
    .join('|');
}

const startOfTerm = '(^|[\\s,;(])';
const terms = startOfTerm + '(' + alternatives(addressTerms.keys()) + ')';
const completedTerm = new RegExp(terms + '(?=$|[\\s,;.()])(\\.?)', 'gi');
const termBeforeSeparator = new RegExp(terms + '(?=[\\s,;.()])(\\.?)', 'gi');
const shortNames = alternatives(new Set([...addressTerms.values(), 'пр.']));
const abbreviationsBeforeName = new RegExp(
  startOfTerm + '(' + shortNames + ')(?:\\s+([а-яё])|([а-яё])(?=[а-яё]))?',
  'gi',
);
const abbreviationsWithoutSpace = new Set(['ул.', 'пр.', 'просп.', 'г.', 'д.']);

export function formatAddress(value: string, finishLastWord: boolean): string {
  const termPattern = finishLastWord || value.endsWith(')') ? completedTerm : termBeforeSeparator;
  const shortened = value.replace(
    termPattern,
    (_, prefix: string, term: string, period: string) => {
      const key = term.toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ');
      const abbreviation = addressTerms.get(key)!;
      return prefix + abbreviation + (abbreviation.endsWith('.') ? '' : period);
    },
  );

  return shortened.replace(
    abbreviationsBeforeName,
    (match, prefix: string, abbreviation: string, spacedLetter?: string, adjacentLetter?: string) => {
      const letter = spacedLetter
        ?? (abbreviationsWithoutSpace.has(abbreviation.toLowerCase()) ? adjacentLetter : undefined);
      return letter ? prefix + abbreviation + ' ' + letter.toUpperCase() : match;
    },
  );
}
